export type MessageKey = keyof typeof messages.ko;
export type Translate = (key: MessageKey, values?: MessageValues) => string;

export function normalizeLocalePreference(value: unknown): LocalePreference {
  return LOCALE_PREFERENCES.includes(value as LocalePreference) ? (value as LocalePreference) : "auto";
}

export function normalizeLocale(value: string | undefined): Locale {
  return value?.toLowerCase().startsWith("ko") ? "ko" : "en";
}

export function getBrowserLocale() {
  const intlLocale = Intl.DateTimeFormat().resolvedOptions().locale;
  if (intlLocale) return intlLocale;
  return process.env.LANG?.split(".")[0]?.replace("_", "-");
}

export function resolveLocale(preference: LocalePreference, browserLocale = getBrowserLocale()): Locale {
  return preference === "auto" ? normalizeLocale(browserLocale) : preference;
}

function interpolate(message: string, values: MessageValues = {}) {
  return message.replace(/\{(\w+)\}/g, (placeholder, key: string) => String(values[key] ?? placeholder));
}

export function createI18n(locale: Locale) {
  const t: Translate = (key, values) => interpolate(messages[locale][key], values);
  return {
    locale,
    t,
    formatDate: (value: Date, options: Intl.DateTimeFormatOptions = {}) =>
      new Intl.DateTimeFormat(locale === "ko" ? "ko-KR" : "en-US", options).format(value),
  };
}

export function getI18n(preferences: RaycastLocalePreferences = {}) {
  return createI18n(resolveLocale(normalizeLocalePreference(preferences.language)));
}
